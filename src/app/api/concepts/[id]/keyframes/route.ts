import { KeyframesRequest } from "@/contracts";
import { db, handle, json, parseBody } from "@/engine/http";
import { generateKeyframes } from "@/engine/services/concepts";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/** Regenerate one shot's keyframe ({shotIdx}) or all of them ({}). */
export const POST = handle(async (req: Request, ctx: RouteContext<"/api/concepts/[id]/keyframes">) => {
  const { id } = await ctx.params;
  const body = await parseBody(req, KeyframesRequest);
  return json(
    await generateKeyframes(await db(), id, { shotIdx: body.shotIdx, reason: "regenerated by the operator" }),
  );
});
